def build_chat_user_prompt(query: str, context: str, history: list = None) -> str:
    hist_text = ""
    if history:
        for turn in history[-4:]:
            role = "用户" if turn.get("role") == "user" else "AI导师"
            hist_text += f"{role}: {turn.get('content')}\n"
    
    return f"""【知识库上下文检索证据】：
{context}

【对话历史】：
{hist_text or '（初次发起对话）'}

用户当前提问：{query}

请基于知识库上下文严格回答，句末加 [n] 角标，文末附【考据依据】。
"""

